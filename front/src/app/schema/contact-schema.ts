import { z } from 'zod';

/**
 * お問い合わせフォームデータのスキーマ。
 *
 * クライアント（react-hook-form）とサーバー（`POST /api/mail/send`）が共有する単一の真実。
 * `.max()` は過大ペイロード（DoS・巨大メール）を抑止するための上限で、
 * クライアント・サーバー双方で同一の制約を保証する。
 */
export const contactSchema = z.object({
    name: z.string().min(1, '名前を入力してください').max(100, '名前は100文字以内で入力してください'),
    // RFC 5321 のメールアドレス最大長（254 文字）を上限とする
    email: z
        .string()
        .email('有効なメールアドレスを入力してください')
        .max(254, 'メールアドレスが長すぎます'),
    subjects: z.string().min(1, '件名を入力してください').max(200, '件名は200文字以内で入力してください'),
    messages: z
        .string()
        .min(1, 'お問い合わせ内容を入力してください')
        .max(5000, 'お問い合わせ内容は5000文字以内で入力してください'),
});
